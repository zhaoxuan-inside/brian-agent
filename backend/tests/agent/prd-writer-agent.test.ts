describe('WriterAgentService.getUserProfile', () => {
  it('TC-WA-016: query existing profile returns correct fields', () => {
    db.prepare(`INSERT INTO writer_agent_user_profile
      (id, created, updated, session_id, language, style, depth, format, additional_preferences)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`)
      .run('id-1', Date.now(), Date.now(), 'session-q1', 'en-US', 'concise', 'shallow', 'TEXT', '{"key":"value"}');

    const input = new GetUserProfileInput({ session_id: 'session-q1' });
    const context = new GetUserProfileContext();
    const output = new GetUserProfileOutput();

    const result = service.getUserProfile(input, context, output);

    expect(result).toBe(true);
    expect(output.user_profile).toBeDefined();
    expect(output.user_profile!.session_id).toBe('session-q1');
    expect(output.user_profile!.language).toBe('en-US');
    expect(output.user_profile!.style).toBe('concise');
    expect(output.user_profile!.depth).toBe('shallow');
    expect(output.user_profile!.format).toBe('TEXT');
    expect(output.user_profile!.additional_preferences).toBe('{"key":"value"}');
  });

  it('TC-WA-017: query non-existing profile returns default', () => {
    const input = new GetUserProfileInput({ session_id: 'nonexistent' });
    const context = new GetUserProfileContext();
    const output = new GetUserProfileOutput();

    const result = service.getUserProfile(input, context, output);

    expect(result).toBe(true);
    expect(output.user_profile).toEqual({
      language: 'zh-CN',
      style: 'clear',
      depth: 'medium',
      format: 'MARKDOWN',
    });
  });

  it('TC-WA-018: additional_preferences saved and retrieved correctly (null case)', () => {
    db.prepare(`INSERT INTO writer_agent_user_profile
      (id, created, updated, session_id, language, style, depth, format, additional_preferences)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`)
      .run('id-null', Date.now(), Date.now(), 'session-null', 'zh-CN', 'clear', 'medium', 'MARKDOWN', null);

    const input = new GetUserProfileInput({ session_id: 'session-null' });
    const context = new GetUserProfileContext();
    const output = new GetUserProfileOutput();

    service.getUserProfile(input, context, output);

    expect(output.user_profile!.additional_preferences).toBeNull();
  });
});

