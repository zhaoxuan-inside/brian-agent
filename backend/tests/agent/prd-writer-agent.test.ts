import Database from 'better-sqlite3';
import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import {
  createWriterAgentService,
  WriterAgentService,
  WriteInput, WriteContext, WriteOutput,
  SaveUserProfileInput, SaveUserProfileContext, SaveUserProfileOutput,
  GetUserProfileInput, GetUserProfileContext, GetUserProfileOutput,
  ConfigWriterAgentInput, ConfigWriterAgentContext, ConfigWriterAgentOutput,
} from '../../src/agent/WriterAgent/WriterAgent';
import type { ChatCompletionRequest } from '../../src/base/LLMWrapper';

let db: Database.Database;
let service: WriterAgentService;
let mockLlmService: { chatCompletion: ReturnType<typeof vi.fn> };

beforeEach(() => {
  db = new Database(':memory:');
  mockLlmService = {
    chatCompletion: vi.fn().mockResolvedValue({
      choices: [{ message: { content: 'This is a generated response.' } }],
      usage: { totalTokens: 50 },
    }),
  };
  service = createWriterAgentService(db, mockLlmService as any);
});

afterEach(() => {
  db.close();
});

function makeAgentResults(count = 2) {
  const results: { agent_id: string; task_content: string; result: string }[] = [];
  for (let i = 0; i < count; i++) {
    results.push({
      agent_id: `agent-${i}`,
      task_content: `Task ${i}: analysis`,
      result: `Result for task ${i}`,
    });
  }
  return results;
}

function makeWriteInput(overrides: Partial<WriteInput> = {}) {
  return new WriteInput({
    work_id: 'work-1',
    interact_id: 'interact-1',
    user_query: 'What is the weather today?',
    agent_results: makeAgentResults(),
    ...overrides,
  });
}

