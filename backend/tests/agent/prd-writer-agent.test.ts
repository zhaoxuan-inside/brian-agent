describe('WriterAgentService.saveUserProfile', () => {
  it('TC-WA-012: first save creates record with all fields', () => {
    const input = new SaveUserProfileInput({
      session_id: 'session-1',
      language: 'en-US',
      style: 'detailed',
      depth: 'deep',
      format: 'JSON',
      additional_preferences: '{"tone":"formal"}',
    });
    const context = new SaveUserProfileContext();
    const output = new SaveUserProfileOutput();

    const result = service.saveUserProfile(input, context, output);

    expect(result).toBe(true);

    const row = db.prepare('SELECT * FROM writer_agent_user_profile WHERE session_id = ?').get('session-1') as Record<string, unknown>;
    expect(row).toBeDefined();
    expect(row.session_id).toBe('session-1');
    expect(row.language).toBe('en-US');
    expect(row.style).toBe('detailed');
    expect(row.depth).toBe('deep');
    expect(row.format).toBe('JSON');
    expect(row.additional_preferences).toBe('{"tone":"formal"}');
  });

  it('TC-WA-013: upsert updates existing record, only specified fields change', () => {
    const input1 = new SaveUserProfileInput({
      session_id: 'session-2',
      language: 'zh-CN',
      style: 'clear',
      depth: 'medium',
      format: 'MARKDOWN',
      additional_preferences: '{}',
    });
    service.saveUserProfile(input1, new SaveUserProfileContext(), new SaveUserProfileOutput());

    const input2 = new SaveUserProfileInput({
      session_id: 'session-2',
      style: 'creative',
    });
    const output2 = new SaveUserProfileOutput();
    service.saveUserProfile(input2, new SaveUserProfileContext(), output2);

    const row = db.prepare('SELECT * FROM writer_agent_user_profile WHERE session_id = ?').get('session-2') as Record<string, unknown>;
    expect(row.style).toBe('creative');
    expect(row.language).toBe('zh-CN');
    expect(row.depth).toBe('medium');
    expect(row.format).toBe('MARKDOWN');
    expect(row.additional_preferences).toBe('{}');
  });

  it('TC-WA-014: upsert can update additional_preferences independently', () => {
    const input1 = new SaveUserProfileInput({
      session_id: 'session-ap',
      language: 'zh-CN',
      style: 'clear',
      depth: 'shallow',
      format: 'TEXT',
    });
    service.saveUserProfile(input1, new SaveUserProfileContext(), new SaveUserProfileOutput());

    const input2 = new SaveUserProfileInput({
      session_id: 'session-ap',
      additional_preferences: '{"new":"val"}',
    });
    service.saveUserProfile(input2, new SaveUserProfileContext(), new SaveUserProfileOutput());

    const row = db.prepare('SELECT * FROM writer_agent_user_profile WHERE session_id = ?').get('session-ap') as Record<string, unknown>;
    expect(row.additional_preferences).toBe('{"new":"val"}');
    expect(row.language).toBe('zh-CN');
  });

  it('TC-WA-015: empty session_id returns false', () => {
    const input = new SaveUserProfileInput({
      session_id: '',
      language: 'en-US',
    });
    const context = new SaveUserProfileContext();
    const output = new SaveUserProfileOutput();

    const result = service.saveUserProfile(input, context, output);

    expect(result).toBe(false);
  });
});

