describe('WriterAgentService.configWriterAgent', () => {
  function getConfig(): Record<string, unknown> {
    return db.prepare('SELECT * FROM writer_agent_config LIMIT 1').get() as Record<string, unknown>;
  }

  it('TC-WA-019: initial config has expected defaults', () => {
    const config = getConfig();
    expect(config.write_prompt_template_id).toBe('');
    expect(config.default_language).toBe('zh-CN');
    expect(config.default_style).toBe('clear');
    expect(config.default_depth).toBe('medium');
    expect(config.default_format).toBe('MARKDOWN');
  });

  it('TC-WA-020: configWriterAgent returns defaults in output when called with no overrides', () => {
    const input = new ConfigWriterAgentInput({});
    const context = new ConfigWriterAgentContext();
    const output = new ConfigWriterAgentOutput();

    const result = service.configWriterAgent(input, context, output);

    expect(result).toBe(true);
    expect(output.write_prompt_template_id).toBe('');
    expect(output.default_language).toBe('zh-CN');
    expect(output.default_style).toBe('clear');
    expect(output.default_depth).toBe('medium');
    expect(output.default_format).toBe('MARKDOWN');
  });

  it('TC-WA-021: update all valid fields persists correctly', () => {
    const input = new ConfigWriterAgentInput({
      write_prompt_template_id: 'tmpl-abc',
      default_language: 'en-US',
      default_style: 'creative',
      default_depth: 'deep',
      default_format: 'JSON',
    });
    const output = new ConfigWriterAgentOutput();

    const result = service.configWriterAgent(input, new ConfigWriterAgentContext(), output);

    expect(result).toBe(true);
    expect(output.write_prompt_template_id).toBe('tmpl-abc');
    expect(output.default_language).toBe('en-US');
    expect(output.default_style).toBe('creative');
    expect(output.default_depth).toBe('deep');
    expect(output.default_format).toBe('JSON');

    const config = getConfig();
    expect(config.write_prompt_template_id).toBe('tmpl-abc');
    expect(config.default_language).toBe('en-US');
    expect(config.default_style).toBe('creative');
    expect(config.default_depth).toBe('deep');
    expect(config.default_format).toBe('JSON');
  });

  it('TC-WA-022: partial update changes only specified fields', () => {
    const input1 = new ConfigWriterAgentInput({
      write_prompt_template_id: 'tmpl-initial',
      default_language: 'fr',
      default_style: 'detailed',
      default_depth: 'shallow',
      default_format: 'TEXT',
    });
    service.configWriterAgent(input1, new ConfigWriterAgentContext(), new ConfigWriterAgentOutput());

    const input2 = new ConfigWriterAgentInput({
      default_language: 'ja',
      default_style: 'concise',
    });
    const output2 = new ConfigWriterAgentOutput();
    service.configWriterAgent(input2, new ConfigWriterAgentContext(), output2);

    expect(output2.default_language).toBe('ja');
    expect(output2.default_style).toBe('concise');

    const config = getConfig();
    expect(config.default_language).toBe('ja');
    expect(config.default_style).toBe('concise');
    expect(config.write_prompt_template_id).toBe('tmpl-initial');
    expect(config.default_depth).toBe('shallow');
    expect(config.default_format).toBe('TEXT');
  });

  it('TC-WA-023: invalid style returns false and does not persist', () => {
    const before = getConfig();

    const input = new ConfigWriterAgentInput({ default_style: 'invalid-style' });
    const output = new ConfigWriterAgentOutput();

    const result = service.configWriterAgent(input, new ConfigWriterAgentContext(), output);

    expect(result).toBe(false);

    const after = getConfig();
    expect(after.default_style).toBe(before.default_style);
  });

  it('TC-WA-024: invalid depth returns false and does not persist', () => {
    const before = getConfig();

    const input = new ConfigWriterAgentInput({ default_depth: 'ultra-deep' });
    const output = new ConfigWriterAgentOutput();

    const result = service.configWriterAgent(input, new ConfigWriterAgentContext(), output);

    expect(result).toBe(false);

    const after = getConfig();
    expect(after.default_depth).toBe(before.default_depth);
  });

  it('TC-WA-025: invalid format returns false and does not persist', () => {
    const before = getConfig();

    const input = new ConfigWriterAgentInput({ default_format: 'XML' });
    const output = new ConfigWriterAgentOutput();

    const result = service.configWriterAgent(input, new ConfigWriterAgentContext(), output);

    expect(result).toBe(false);

    const after = getConfig();
    expect(after.default_format).toBe(before.default_format);
  });

  it('TC-WA-026: all valid style values accepted', () => {
    for (const style of ['clear', 'concise', 'detailed', 'creative']) {
      const input = new ConfigWriterAgentInput({ default_style: style });
      const result = service.configWriterAgent(input, new ConfigWriterAgentContext(), new ConfigWriterAgentOutput());
      expect(result).toBe(true);
    }
  });

  it('TC-WA-027: all valid depth values accepted', () => {
    for (const depth of ['shallow', 'medium', 'deep']) {
      const input = new ConfigWriterAgentInput({ default_depth: depth });
      const result = service.configWriterAgent(input, new ConfigWriterAgentContext(), new ConfigWriterAgentOutput());
      expect(result).toBe(true);
    }
  });

  it('TC-WA-028: all valid format values accepted', () => {
    for (const format of ['TEXT', 'MARKDOWN', 'JSON']) {
      const input = new ConfigWriterAgentInput({ default_format: format });
      const result = service.configWriterAgent(input, new ConfigWriterAgentContext(), new ConfigWriterAgentOutput());
      expect(result).toBe(true);
    }
  });
});
