// write
// ============================================================================
describe('WriterAgentService.write', () => {
  it('TC-WA-001: basic write with agent_results calls LLM and returns response in MARKDOWN', async () => {
    const input = makeWriteInput();
    const context = new WriteContext();
    const output = new WriteOutput();

    const result = await service.write(input, context, output);

    expect(result).toBe(true);
    expect(output.response).toBe('This is a generated response.');
    expect(output.response_format).toBe('MARKDOWN');
    expect(mockLlmService.chatCompletion).toHaveBeenCalledTimes(1);

    const req = mockLlmService.chatCompletion.mock.calls[0][0] as ChatCompletionRequest;
    expect(req.messages).toHaveLength(2);
    expect(req.response_format).toBeUndefined();
    expect(req.messages[0].role).toBe('system');
    expect(req.messages[1].role).toBe('user');
    expect(req.messages[1].content).toContain('What is the weather today?');
    expect(req.messages[1].content).toContain('Task 0: analysis');
    expect(req.messages[1].content).toContain('Result for task 0');
    expect(req.messages[1].content).toContain('Task 1: analysis');
    expect(req.messages[1].content).toContain('Result for task 1');
  });

  it('TC-WA-002: write with empty agent_results calls LLM with fallback results text', async () => {
    const input = makeWriteInput({ agent_results: [] });
    const context = new WriteContext();
    const output = new WriteOutput();

    await service.write(input, context, output);

    expect(output.response).toBe('This is a generated response.');
    expect(mockLlmService.chatCompletion).toHaveBeenCalledTimes(1);

    const req = mockLlmService.chatCompletion.mock.calls[0][0] as ChatCompletionRequest;
    expect(req.messages[1].content).toContain('No results available.');
  });

  it('TC-WA-003: write when LLM returns empty content uses resultsText as fallback', async () => {
    mockLlmService.chatCompletion.mockResolvedValueOnce({
      choices: [{ message: { content: '' } }],
      usage: { totalTokens: 0 },
    });

    const input = makeWriteInput({ agent_results: [] });
    const context = new WriteContext();
    const output = new WriteOutput();

    await service.write(input, context, output);

    expect(output.response).toBe('No results available.');
    expect(output.token_usage).toBe(0);
  });

  it('TC-WA-004: write without llmService uses fallback response', async () => {
    const svc = createWriterAgentService(db);
    const input = makeWriteInput();
    const context = new WriteContext();
    const output = new WriteOutput();

    const result = await svc.write(input, context, output);

    expect(result).toBe(true);
    expect(output.response).toContain('## What is the weather today?');
    expect(output.response).toContain('### Task 0: analysis');
    expect(output.response).toContain('Result for task 0');
    expect(output.response).toContain('Generated by WriterAgent');
    expect(output.response_format).toBe('MARKDOWN');
  });

  it('TC-WA-005: write without llmService and without agent_results uses fallback with defaults', async () => {
    const svc = createWriterAgentService(db);
    const input = makeWriteInput({ agent_results: [] });
    const context = new WriteContext();
    const output = new WriteOutput();

    await svc.write(input, context, output);

    expect(output.response).toContain('## What is the weather today?');
    expect(output.response).toContain('No results available.');
    expect(output.response).toContain('Generated by WriterAgent');
  });

  it('TC-WA-006: write sets elapsed_ms and token_usage on output', async () => {
    const input = makeWriteInput();
    const context = new WriteContext();
    const output = new WriteOutput();

    await service.write(input, context, output);

    expect(typeof output.elapsed_ms).toBe('number');
    expect(output.elapsed_ms!).toBeGreaterThanOrEqual(0);
    expect(output.token_usage).toBe(50);
  });

  it('TC-WA-007: custom user_preferences override default style in LLM system prompt', async () => {
    const input = makeWriteInput({
      user_preferences: { style: 'creative', language: 'en-US', depth: 'deep' },
    });
    const context = new WriteContext();
    const output = new WriteOutput();

    await service.write(input, context, output);

    expect(mockLlmService.chatCompletion).toHaveBeenCalledTimes(1);
    const req = mockLlmService.chatCompletion.mock.calls[0][0] as ChatCompletionRequest;
    const systemMsg = req.messages.find(m => m.role === 'system')!.content;

    expect(systemMsg).toContain('Style: creative');
    expect(systemMsg).toContain('Language: en-US');
    expect(systemMsg).toContain('Depth: deep');
    expect(systemMsg).toContain('Write creatively with engaging language.');
  });

  it('TC-WA-008: partial user_preferences fill defaults for unspecified fields', async () => {
    const input = makeWriteInput({
      user_preferences: { style: 'concise' },
    });
    const context = new WriteContext();
    const output = new WriteOutput();

    await service.write(input, context, output);

    const req = mockLlmService.chatCompletion.mock.calls[0][0] as ChatCompletionRequest;
    const systemMsg = req.messages.find(m => m.role === 'system')!.content;

    expect(systemMsg).toContain('Style: concise');
    expect(systemMsg).toContain('Language: zh-CN');
    expect(systemMsg).toContain('Depth: medium');
    expect(systemMsg).toContain('Format: MARKDOWN');
    expect(systemMsg).toContain('Be concise and to the point');
  });

  it('TC-WA-009: LLM call fails falls back to buildFallbackResponse', async () => {
    mockLlmService.chatCompletion.mockRejectedValueOnce(new Error('LLM timeout'));

    const input = makeWriteInput();
    const context = new WriteContext();
    const output = new WriteOutput();

    const result = await service.write(input, context, output);

    expect(result).toBe(true);
    expect(output.response).toContain('## What is the weather today?');
    expect(output.response).toContain('### Task 0: analysis');
    expect(output.response).toContain('Generated by WriterAgent');
    expect(output.token_usage).toBe(0);
    expect(output.response_format).toBe('MARKDOWN');
  });

  it('TC-WA-010: LLM call fails with empty agent_results fills fallback', async () => {
    mockLlmService.chatCompletion.mockRejectedValueOnce(new Error('API error'));

    const input = makeWriteInput({ agent_results: [] });
    const context = new WriteContext();
    const output = new WriteOutput();

    await service.write(input, context, output);

    expect(output.response).toContain('No results available.');
    expect(output.response).toContain('Generated by WriterAgent');
    expect(output.token_usage).toBe(0);
  });

  it('TC-WA-011: user_query can be empty string', async () => {
    const input = makeWriteInput({ user_query: '' });
    const context = new WriteContext();
    const output = new WriteOutput();

    await service.write(input, context, output);

    const req = mockLlmService.chatCompletion.mock.calls[0][0] as ChatCompletionRequest;
    expect(req.messages[1].content).toContain('User question: ');
  });
});

